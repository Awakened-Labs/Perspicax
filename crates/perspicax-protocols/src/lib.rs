//! perspicax's own Wayland protocols, for the server and the client side.
//!
//! Each is a channel between the compositor and one of perspicax's own
//! programs, and carries only what no standard protocol does:
//!
//! - `perspicax-shell-v1` (see `protocols/perspicax-shell-v1.xml`), to
//!   `perspicax-shell`: that the person asked for a menu, that the config
//!   changed, that the session should end, from version 2 the keyboard's
//!   layouts and which is in use, from version 3 that the person asked for
//!   a pie, from version 4 a volume key, and from version 5 what is made
//!   of each window and what the person chose in its menu: sticky, on top,
//!   rolled up, sent to a workspace. The shell's surfaces, taskbar and pager all speak standard
//!   protocols, so any piece of it can be replaced by a program that knows
//!   nothing of this one; a window's menu names the window and the
//!   workspace by the handles those protocols gave it.
//! - `perspicax-settings-v1` (see `protocols/perspicax-settings-v1.xml`),
//!   to `perspicax-settings`: the next chord the person presses, as the
//!   compositor reads it, for the app to bind.
//!
//! The bindings are generated by `wayland-scanner`, as `wayland-protocols`
//! generates the standard ones: the `server` feature for the compositor,
//! `client` for the programs. A crate of its own so that both sides compile
//! the same XML, and neither has to depend on the other.

#![cfg_attr(docsrs, feature(doc_cfg))]

/// One protocol's two sides, generated from its XML at `$xml`, a path from
/// this crate's root, naming the objects of the standard protocols at
/// `$imports` as `wayland-protocols-wlr` names `wayland-protocols`' own.
macro_rules! generated {
    ($xml:tt, [$($imports:path),*]) => {
        #[cfg(feature = "client")]
        pub use self::generated::client;
        #[cfg(feature = "server")]
        pub use self::generated::server;

        // The scanner's macros read the XML without telling cargo, so an
        // edit to it alone would not rebuild this crate. Reading it here
        // does: rustc records what `include_str!` reads.
        const _: &str = include_str!(concat!("../", $xml));

        // The scanner's output, as `wayland-protocols` includes its own.
        // The interface tables it emits for libwayland are statics holding
        // raw pointers, declared `unsafe impl Sync` and read through
        // `unsafe { &... }`: generated, never written by hand, and the
        // reason this crate holds `deny` rather than the workspace's
        // `forbid`.
        #[allow(
            unsafe_code,
            reason = "wayland-scanner's interface tables are raw-pointer statics"
        )]
        mod generated {
            #![allow(
                dead_code,
                non_camel_case_types,
                unused_unsafe,
                unused_variables,
                non_upper_case_globals,
                non_snake_case,
                unused_imports,
                missing_docs,
                clippy::all,
                reason = "generated by wayland-scanner"
            )]

            #[cfg(feature = "client")]
            pub mod client {
                //! The program's side.
                use wayland_client;
                use wayland_client::protocol::*;
                $(use $imports::{client::*};)*

                pub mod __interfaces {
                    use wayland_client::protocol::__interfaces::*;
                    $(use $imports::{client::__interfaces::*};)*
                    wayland_scanner::generate_interfaces!($xml);
                }
                use self::__interfaces::*;

                wayland_scanner::generate_client_code!($xml);
            }

            #[cfg(feature = "server")]
            pub mod server {
                //! The compositor's side.
                use wayland_server;
                use wayland_server::protocol::*;
                $(use $imports::{server::*};)*

                pub mod __interfaces {
                    use wayland_server::protocol::__interfaces::*;
                    $(use $imports::{server::__interfaces::*};)*
                    wayland_scanner::generate_interfaces!($xml);
                }
                use self::__interfaces::*;

                wayland_scanner::generate_server_code!($xml);
            }
        }
    };
}

/// `perspicax-shell-v1`: menus and pies asked for, a config changed, a
/// session ended, the keyboard's layouts, the volume keys, a window made
/// sticky, kept on top, rolled up or sent to a workspace.
pub mod shell {
    /// `perspicax_shell_v1`, whose interface is at version 5.
    pub mod v1 {
        generated!(
            "protocols/perspicax-shell-v1.xml",
            [
                wayland_protocols::ext::workspace::v1,
                wayland_protocols_wlr::foreign_toplevel::v1
            ]
        );
    }
}

/// `perspicax-settings-v1`: the next chord pressed, for the settings app to
/// bind.
pub mod settings {
    /// `perspicax_settings_v1` and `perspicax_chord_capture_v1`, at
    /// version 1.
    pub mod v1 {
        generated!("protocols/perspicax-settings-v1.xml", []);
    }
}
